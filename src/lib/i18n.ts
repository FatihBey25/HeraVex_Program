import type { GameStatus, TaskItem } from "../types";

export type AppLanguage = "en" | "tr" | "fr" | "es";
export type DetailTab =
  | "overview"
  | "notes"
  | "tasks"
  | "versions"
  | "release"
  | "moodboard"
  | "integrations"
  | "storesync";

export function statusLabel(language: AppLanguage, status: GameStatus) {
  return copy[language].statuses[status];
}

export function tabLabel(language: AppLanguage, tab: DetailTab) {
  return copy[language].tabs[tab];
}

export function priorityLabel(priority: 1 | 2 | 3, language: AppLanguage) {
  if (priority === 3) return copy[language].high;
  if (priority === 2) return copy[language].medium;
  return copy[language].low;
}

export function localeForLanguage(language: AppLanguage) {
  if (language === "tr") return "tr-TR";
  if (language === "fr") return "fr-FR";
  if (language === "es") return "es-ES";
  return "en-US";
}

export function dueDateTimestamp(task: Pick<TaskItem, "dueDate">) {
  if (!task.dueDate) return null;
  const parsed = Date.parse(`${task.dueDate}T23:59:59`);
  return Number.isNaN(parsed) ? null : parsed;
}

export function compareTasks(a: TaskItem, b: TaskItem) {
  if (a.done !== b.done) return Number(a.done) - Number(b.done);

  const aDue = dueDateTimestamp(a);
  const bDue = dueDateTimestamp(b);

  if (aDue !== null && bDue !== null && aDue !== bDue) return aDue - bDue;
  if (aDue !== null && bDue === null) return -1;
  if (aDue === null && bDue !== null) return 1;

  if (a.priority !== b.priority) return b.priority - a.priority;
  return a.title.localeCompare(b.title, "tr");
}

export function taskDeadlineLabel(task: Pick<TaskItem, "done" | "dueDate">, language: AppLanguage) {
  if (!task.dueDate) return copy[language].noDeadline;

  const endOfDueDate = dueDateTimestamp(task);
  if (endOfDueDate === null) return copy[language].noDeadline;

  const msPerDay = 24 * 60 * 60 * 1000;
  const daysLeft = Math.floor((endOfDueDate - Date.now()) / msPerDay);

  if (task.done) {
    return copy[language].dueOn(new Date(task.dueDate).toLocaleDateString(localeForLanguage(language)));
  }

  if (daysLeft < 0) return copy[language].overdue;
  if (daysLeft === 0) return copy[language].dueToday;
  if (daysLeft <= 3) return copy[language].dueInDays(daysLeft);
  return copy[language].dueOn(new Date(task.dueDate).toLocaleDateString(localeForLanguage(language)));
}

export function dueToneClass(task: Pick<TaskItem, "done" | "dueDate">) {
  if (!task.dueDate) return "due-chip-neutral";
  if (task.done) return "due-chip-done";

  const endOfDueDate = dueDateTimestamp(task);
  if (endOfDueDate === null) return "due-chip-neutral";

  const daysLeft = Math.floor((endOfDueDate - Date.now()) / (24 * 60 * 60 * 1000));
  if (daysLeft < 0) return "due-chip-overdue";
  if (daysLeft <= 3) return "due-chip-soon";
  return "due-chip-neutral";
}

export function statusToneClass(status: GameStatus) {
  if (status === "Yayinda")      return "status-tag-live";
  if (status === "Yayina Hazir") return "status-tag-ready";
  if (status === "Beta")         return "status-tag-beta";
  if (status === "Alpha")        return "status-tag-alpha";
  if (status === "Demo")         return "status-tag-demo";
  if (status === "Prototip")     return "status-tag-proto";
  return "status-tag-idea";
}

export function formatFileSize(size: number) {
  if (size < 1024) return `${size} B`;
  if (size < 1024 * 1024) return `${(size / 1024).toFixed(1)} KB`;
  if (size < 1024 * 1024 * 1024) return `${(size / (1024 * 1024)).toFixed(1)} MB`;
  return `${(size / (1024 * 1024 * 1024)).toFixed(2)} GB`;
}

